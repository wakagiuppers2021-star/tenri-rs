def _rows(opts, tag):
    """選択肢を、2つずつ2行にならべる。1行は28字までにおさめる。"""
    assert len(opts) == 4, (tag, opts)
    rows = [f'ア {opts[0]}　イ {opts[1]}', f'ウ {opts[2]}　エ {opts[3]}']
    assert all(len(r) <= 28 for r in rows), (tag, rows)
    return '\n'.join(rows)


def _d(d, head):
    return {**d, 'head': head} if head else d


def J(meaning, hint, ans, tip='', head=None):
    """意味から二字の熟語（二字目がヒント）。"""
    assert ans[1] == hint
    return _d(dict(kind='short', q=f'{meaning}［{hint}］', ans=ans, cells=2, meta=dict(t='J', hint=hint),
                   ex=f'「{ans}」。{tip}'), head)


def K(meaning, opts, ans, tip='', head=None):
    """意味に合う慣用句・ことわざを選ぶ。選択肢は慣用句。"""
    right = opts['アイウエ'.index(ans)]
    return _d(dict(kind='short', q=f'{meaning}\n{_rows(opts, meaning)}', ans=ans, cells=1,
                   meta=dict(t='K', idiom=right), ex=f'答えは「{right}」。{tip}'), head)


def L(idiom, opts, ans, tip='', head=None):
    """慣用句・ことわざの意味を選ぶ。選択肢は意味。"""
    right = opts['アイウエ'.index(ans)]
    return _d(dict(kind='short', q=f'「{idiom}」\n{_rows(opts, idiom)}', ans=ans, cells=1,
                   meta=dict(t='L', idiom=idiom), ex=f'「{idiom}」＝{right}。{tip}'), head)


def C(word, typ, tip, head=None):
    """熟語の組み立て（ア〜カ）。"""
    return _d(dict(kind='short', q=f'「{word}」', ans=typ, cells=1, meta=dict(t='C', word=word), ex=f'「{word}」は、{tip}'), head)


def A(word, anto, tip='', head=None):
    """対義語。"""
    return _d(dict(kind='short', q=f'「{word}」', ans=anto, cells=2, meta=dict(t='A', word=word),
                   ex=f'「{word}」の対義語は「{anto}」。{tip}'), head)


def Y(pre, ans, post, meaning, word, tip='', head=None):
    """四字熟語の、〔　〕に入る漢字一字。"""
    assert pre + ans + post == word and len(word) == 4
    return _d(dict(kind='short', q=f'{pre}〔　〕{post}（{meaning}）', ans=ans, cells=1, meta=dict(t='Y', word=word, idx=len(pre)),
                   ex=f'「{word}」＝{meaning}。{tip}'), head)


def I(pre, ans, post, meaning, idiom, tip='', head=None):
    """慣用句・ことわざの、〔　〕に入る漢字（送りがなつきでもよい）。"""
    assert pre + ans + post == idiom or ans in idiom, (pre, ans, post, idiom)
    return _d(dict(kind='short', q=f'{pre}〔　〕{post}（{meaning}）', ans=ans, cells=len(ans),
                   meta=dict(t='I', idiom=idiom, pre=pre, post=post), ex=f'「{idiom}」＝{meaning}。{tip}'), head)


def M(sent, word, opts, ans, tip='', head=None):
    """比喩的に使われた言葉の意味を選ぶ。"""
    return _d(dict(kind='short', q=f'「{sent}」の「{word}」\n{_rows(opts, sent)}', ans=ans, cells=1,
                   meta=dict(t='M'), ex=f'「{sent}」の「{word}」は、「{opts["アイウエ".index(ans)]}」の意味。{tip}'), head)


def GS(sent, word, ans, meaning=None, kata=None, head=None):
    """語群（head に書く）から選ぶ。meaning があれば、〔　〕に入る語（意味つき）。kata があれば、{カタカナ語} の意味。"""
    q = f'{sent}（{meaning}）' if meaning else sent
    return _d(dict(kind='short', q=q, ans=ans, cells=1, wide=bool(meaning), meta=dict(t='GS', word=word, kata=kata),
                   ex=f'答えは「{word}」。' + (f'「{kata}」は「{word}」の意味。' if kata else f'（{meaning}）という意味の言葉。')), head)


def YJ(sent, word, hira, tip='', head=None):
    """――の意味と同じような意味の四字熟語を、語群から選び、漢字に直す。"""
    return _d(dict(kind='short', q=sent, ans=word, cells=4, wide=True, meta=dict(t='YJ', word=word, hira=hira),
                   ex=f'「{hira}」は「{word}」。{tip}'), head)


def NF(stems, opts, ans, tip='', head=None):
    """4つの慣用句の〔　〕に入らない言葉を、5つの選択肢から選ぶ。stems は (前, 入る漢字, 後) の4つ。"""
    assert len(stems) == 4 and len(opts) == 5
    lines = ['・' + '　・'.join(f'{a}〔　〕{b}' for a, _, b in stems[i:i + 2]) for i in (0, 2)]
    row = '　'.join(f'{s} {o}' for s, o in zip('アイウエオ', opts))
    fills = '　'.join(f'「{a}{c}{b}」' for a, c, b in stems)
    return _d(dict(kind='short', q='\n'.join(lines + [row]), ans=ans, cells=1, meta=dict(t='NF', stems=stems, opts=opts),
                   ex=f'入るのは、{fills}の{"、".join(c for _, c, _ in stems)}。残った「{opts["アイウエオ".index(ans)]}」が答え。{tip}'), head)


def HK(poem, hint, opts, ans, tip='', head=None):
    """俳句の〔　〕に入る言葉を選ぶ。"""
    return _d(dict(kind='short', q=f'{poem}\n（{hint}）\n{_rows(opts, poem)}', ans=ans, cells=1,
                   meta=dict(t='HK', poem=poem, opts=opts), ex=f'答えは「{opts["アイウエ".index(ans)]}」。{tip}'), head)


def UW(idiom, sents, ans, tip='', head=None):
    """慣用句・ことわざが、正しい意味で使われている文を選ぶ。"""
    assert len(sents) == 4
    body = '\n'.join(f'{s} {t}' for s, t in zip('アイウエ', sents))
    return _d(dict(kind='short', q=f'「{idiom}」\n{body}', ans=ans, cells=1, wide=True, meta=dict(t='UW', idiom=idiom, sents=sents),
                   ex=f'「{idiom}」を正しく使っているのは、{ans}。{tip}'), head)


def IC(sent, used, ans, right, tip='', head=None):
    """――のことわざ・慣用句が正しければ○。まちがっていれば、正しいものを、語群から選ぶ。"""
    ok = ans == '○'
    return _d(dict(kind='short', q=sent, ans=ans, cells=1, wide=True, meta=dict(t='IC', used=used, right=right, ok=ok),
                   ex=(f'「{used}」は、この文で正しい。' if ok else f'この文には、「{right}」が合う。「{used}」は、別の場面で使う言葉。') + tip), head)


