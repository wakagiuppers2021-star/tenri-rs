def _rows(opts, tag):
    """選択肢を、2つずつ2行にならべる。1行は28字までにおさめる。"""
    assert len(opts) == 4, (tag, opts)
    rows = [f'ア {opts[0]}　イ {opts[1]}', f'ウ {opts[2]}　エ {opts[3]}']
    assert all(len(r) <= 28 for r in rows), (tag, rows)
    return '\n'.join(rows)


def _d(d, head):
    return {**d, 'head': head} if head else d


def J(meaning, hint, ans, tip='', head=None):
    """意味から二字の熟語（二字目がヒント）。"""
    assert ans[1] == hint
    return _d(dict(kind='short', q=f'{meaning}［{hint}］', ans=ans, cells=2, meta=dict(t='J', hint=hint),
                   ex=f'「{ans}」。{tip}'), head)


def K(meaning, opts, ans, tip='', head=None):
    """意味に合う慣用句・ことわざを選ぶ。選択肢は慣用句。"""
    right = opts['アイウエ'.index(ans)]
    return _d(dict(kind='short', q=f'{meaning}\n{_rows(opts, meaning)}', ans=ans, cells=1,
                   meta=dict(t='K', idiom=right), ex=f'答えは「{right}」。{tip}'), head)


def L(idiom, opts, ans, tip='', head=None):
    """慣用句・ことわざの意味を選ぶ。選択肢は意味。"""
    right = opts['アイウエ'.index(ans)]
    return _d(dict(kind='short', q=f'「{idiom}」\n{_rows(opts, idiom)}', ans=ans, cells=1,
                   meta=dict(t='L', idiom=idiom), ex=f'「{idiom}」＝{right}。{tip}'), head)


def C(word, typ, tip, head=None):
    """熟語の組み立て（ア〜カ）。"""
    return _d(dict(kind='short', q=f'「{word}」', ans=typ, cells=1, meta=dict(t='C', word=word), ex=f'「{word}」は、{tip}'), head)


def A(word, anto, tip='', head=None):
    """対義語。"""
    return _d(dict(kind='short', q=f'「{word}」', ans=anto, cells=2, meta=dict(t='A', word=word),
                   ex=f'「{word}」の対義語は「{anto}」。{tip}'), head)


def Y(pre, ans, post, meaning, word, tip='', head=None):
    """四字熟語の、〔　〕に入る漢字一字。"""
    assert pre + ans + post == word and len(word) == 4
    return _d(dict(kind='short', q=f'{pre}〔　〕{post}（{meaning}）', ans=ans, cells=1, meta=dict(t='Y', word=word, idx=len(pre)),
                   ex=f'「{word}」＝{meaning}。{tip}'), head)


def I(pre, ans, post, meaning, idiom, tip='', head=None):
    """慣用句・ことわざの、〔　〕に入る漢字（送りがなつきでもよい）。"""
    assert pre + ans + post == idiom or ans in idiom, (pre, ans, post, idiom)
    return _d(dict(kind='short', q=f'{pre}〔　〕{post}（{meaning}）', ans=ans, cells=len(ans),
                   meta=dict(t='I', idiom=idiom, pre=pre, post=post), ex=f'「{idiom}」＝{meaning}。{tip}'), head)


def M(sent, word, opts, ans, tip='', head=None):
    """比喩的に使われた言葉の意味を選ぶ。"""
    return _d(dict(kind='short', q=f'「{sent}」の「{word}」\n{_rows(opts, sent)}', ans=ans, cells=1,
                   meta=dict(t='M'), ex=f'「{sent}」の「{word}」は、「{opts["アイウエ".index(ans)]}」の意味。{tip}'), head)


