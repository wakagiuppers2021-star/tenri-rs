def _tick(p, q, size=.28):
    """辺 pq の真ん中に、等しい長さの印（短い線）。"""
    mx, my = (p[0] + q[0]) / 2, (p[1] + q[1]) / 2
    dx, dy = q[0] - p[0], q[1] - p[1]
    n = math.hypot(dx, dy)
    nx, ny = -dy / n * size, dx / n * size
    return ('line', _r((mx - nx, my - ny)), _r((mx + nx, my + ny)), dict(w=1.1))


