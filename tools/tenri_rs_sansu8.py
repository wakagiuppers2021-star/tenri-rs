FOLD_ANGLE = 40                                               # 角BDF（度）


def _r(p):
    return (round(p[0], 4), round(p[1], 4))


def _fold_points():
    """三角定規ABC（B＝90度、C＝30度）を、直線DEで折って、頂点AをBC上の点Fにかさねる。"""
    h = 5.0
    A, B, C = (0.0, h), (0.0, 0.0), (h * math.sqrt(3), 0.0)
    t = math.radians(FOLD_ANGLE)
    d = h * math.cos(t) / (1 + math.cos(t))                   # BD。DA＝DF から
    D = (0.0, d)
    F = (d * math.tan(t), 0.0)
    ux, uy = C[0] - A[0], C[1] - A[1]
    fx, fy = F[0] - A[0], F[1] - A[1]
    s = (F[0] ** 2 + F[1] ** 2 - A[0] ** 2 - A[1] ** 2 - 2 * (A[0] * fx + A[1] * fy)) / (2 * (ux * fx + uy * fy))   # EA＝EF
    E = (A[0] + s * ux, A[1] + s * uy)
    return {k: _r(v) for k, v in dict(A=A, B=B, C=C, D=D, E=E, F=F).items()}


def _dirs(P, v, a, b):
    """頂点 v から、点 a、点 b へ向かう向き（度）。"""
    f = lambda q: round(math.degrees(math.atan2(P[q][1] - P[v][1], P[q][0] - P[v][0])), 3)
    return f(a), f(b)


