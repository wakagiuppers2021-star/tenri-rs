import math


# 図（汎用の図 geo の部品）。長さはcmの座標。
def _tri_angles(base, ap, aq):
    """底辺PQ（長さ base）で、Pの角が ap 度、Qの内角が aq 度の三角形の、頂点Rの座標。"""
    ar = 180 - ap - aq
    pr = base * math.sin(math.radians(aq)) / math.sin(math.radians(ar))
    return (round(pr * math.cos(math.radians(ap)), 4), round(pr * math.sin(math.radians(ap)), 4))


