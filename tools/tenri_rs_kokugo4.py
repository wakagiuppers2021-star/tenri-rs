NOTE_STD = '作文の定番の問題で作った独自教材（過去問の転載ではありません）'
LEAD = '次の条件にしたがって、作文を書きなさい。原稿用紙は、縦書きで、一行目の一番上のますから書き始めなさい。'
FORMAT = '題名や名前は書かず、段落のはじめは一ますあけて書くこと。'


def kan(n):
    """整数（999まで）を、漢数字にする。"""
    d = '〇一二三四五六七八九'
    h, r = divmod(n, 100)
    t, u = divmod(r, 10)
    return (('' if h == 1 else d[h]) + '百' if h else '') + (('' if t == 1 else d[t]) + '十' if t else '') + (d[u] if u else '')


def LIM(lo, hi):
    return f'{kan(lo)}字以上、{kan(hi)}字以内で書くこと。'


def ESSAY(title, year, topic, conds, sample, points, lo, hi, style, paras, must=(), material=None, memo=None, note=None, fmt=None, **meta):
    """作文の1セット。sample は、例文（段落は \\n で区切る）。points は、解説のポイント（\\n で区切る）。"""
    conds = list(conds)
    conds.insert(0, LIM(lo, hi))
    conds.append(fmt or FORMAT)
    d = dict(year=year, title=title, lead=LEAD,
             essay=dict(topic=topic, conds=conds, material=material, memo=memo or ['はじめ', 'なか', 'おわり']),
             qs=[dict(kind='essay', q=topic, ans=sample, ex=points,
                      meta=dict(t='ESSAY', lo=lo, hi=hi, style=style, paras=paras, must=list(must), **meta))])
    if note or year is None:
        d['note'] = note or NOTE_STD
    return d


