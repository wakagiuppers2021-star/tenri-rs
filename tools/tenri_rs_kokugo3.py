def NAI2(target, ttag, opts, ans, tip='', head=None):
    """「ない」の使い方（aux＝打ち消しの助動詞／adj＝存在しない意味の形容詞／hojo＝形容詞の一部）が、target と同じものを選ぶ。"""
    body = '\n'.join(f'{k} {t}' for k, (t, _) in zip('アイウエ', opts))
    name = {'aux': '打ち消しの助動詞', 'adj': '存在しない意味の形容詞', 'hojo': '形容詞の一部'}
    return _d(dict(kind='short', q=f'{target}\n{body}', ans=ans, cells=1, wide=True, meta=dict(t='NAI2', target=target, ttag=ttag, opts=opts),
                   ex=f'「{target.replace("{", "").replace("}", "")}」は{name[ttag]}。' + '　'.join(f'{k}＝{name[g]}' for k, (_, g) in zip('アイウエ', opts)) + f'。{tip}'), head)


def RHS(target, ttag, opts, ans, tip='', head=None):
    """target と同じ表現（直喩・隠喩・擬人法）の文を選ぶ。opts は (文, 表現) の4つ。"""
    body = '\n'.join(f'{k} {t}' for k, (t, _) in zip('アイウエ', opts))
    return _d(dict(kind='short', q=f'「{target}」\n{body}', ans=ans, cells=1, wide=True, meta=dict(t='RHS', target=target, ttag=ttag, opts=opts),
                   ex=f'「{target}」は{ttag}。' + '　'.join(f'{k}＝{g}' for k, (_, g) in zip('アイウエ', opts)) + f'。{tip}'), head)


def RP(s1, s2, n, ans, must, tip='', head=None):
    """言いかえ：アの文と同じ意味になるように、イの文の〔　〕に入る言葉を、n字で書く。must は、その語をふくむ文を形態素解析したときに出てくる語（検算用）。"""
    return _d(dict(kind='short', q=f'ア　{s1}\nイ　{s2}（{"一二三四五六七八"[n - 1]}字）', ans=ans, cells=n,
                   meta=dict(t='RP', s1=s1, s2=s2, n=n, must=must), ex=f'答えは「{ans}」。{tip}'), head)


