def KAK(slash, ans, tip='', head=None):
    """修飾語がかかる文節。slash は、「／」で文節を区切り、かかる側（下線部）を {…} でかこんだ文。"""
    return _d(dict(kind='short', q=slash.replace('／', ''), ans=ans, cells=len(ans), meta=dict(t='KAK', slash=slash),
                   ex=f'「{ans}」にかかる。{tip}'), head)


def ID(sent, ans, kind, tip='', head=None):
    """助動詞・接尾語などの識別（kind は NAI・SOU・YOU・RAS）。"""
    return _d(dict(kind='short', q=sent, ans=ans, cells=1, meta=dict(t=kind), ex=f'答えは「{ans}」。{tip}'), head)


def COMP(sent, ans, tip='', head=None):
    """文の成分。"""
    return _d(dict(kind='short', q=sent, ans=ans, cells=1, meta=dict(t='COMP'), ex=f'答えは「{ans}」。{tip}'), head)


def _t(q):
    import re
    return re.search(r'\{(.+?)\}', q).group(1)


