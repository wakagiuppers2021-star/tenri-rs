def _plain(s):
    return s.replace('{', '').replace('}', '').replace('／', '')


def _d(d, head):
    return {**d, 'head': head} if head else d


def _opts(opts, tag):
    assert len(opts) == 4, (tag, opts)
    row = '　'.join(f'{s} {o}' for s, o in zip('アイウエ', opts))
    assert len(row) <= 28, (tag, row)
    return row


def NO(sent, ans, tip='', head=None):
    """「の」の用法（ア 主語 イ 連体修飾 ウ 体言の代用 エ 同格）。"""
    return _d(dict(kind='short', q=sent, ans=ans, cells=1, meta=dict(t='NO'), ex=f'答えは「{ans}」。{tip}'), head)


def BUN(slash, tip='', head=None):
    """文節の数。slash は、「／」で文節を区切った文。"""
    n = len(slash.split('／'))
    return _d(dict(kind='short', q=f'「{_plain(slash)}」', ans=str(n), cells=1, meta=dict(t='BUN', slash=slash),
                   ex=f'{slash}　で、{n}文節。{tip}'), head)


def SV(slash, subj, pred, tip='', head=None):
    """主語と述語（文節で）。"""
    return _d(dict(kind='short', q=f'「{_plain(slash)}」', boxes=[('主語', 84), ('述語', 84)], ans=f'{subj}　{pred}',
                   meta=dict(t='SV', slash=slash, subj=subj, pred=pred), ex=f'{slash}　主語は「{subj}」、述語は「{pred}」。{tip}'), head)


def PT(sent, opts, ans, tip='', head=None):
    """助詞を選ぶ。"""
    right = opts['アイウエ'.index(ans)]
    return _d(dict(kind='short', q=f'{sent}\n{_opts(opts, sent)}', ans=ans, cells=1, meta=dict(t='PT', opts=opts),
                   ex=f'答えは「{right}」。{tip}'), head)


def CJ(sent, opts, ans, rel, tip='', head=None):
    """接続語を選ぶ。rel は、前後のつながり方。"""
    right = opts['アイウエ'.index(ans)]
    return _d(dict(kind='short', q=f'{sent}\n{_opts(opts, sent)}', ans=ans, cells=1, meta=dict(t='CJ', opts=opts, rel=rel),
                   ex=f'答えは「{right}」（{rel}）。{tip}'), head)


def POS(sent, ans, tip='', head=None):
    """品詞。"""
    return _d(dict(kind='short', q=sent, ans=ans, cells=1, meta=dict(t='POS'), ex=f'答えは「{ans}」。{tip}'), head)


def AUX(sent, ans, tip='', head=None):
    """れる・られる・せる・させる の意味。"""
    return _d(dict(kind='short', q=sent, ans=ans, cells=1, meta=dict(t='AUX'), ex=f'答えは「{ans}」。{tip}'), head)


