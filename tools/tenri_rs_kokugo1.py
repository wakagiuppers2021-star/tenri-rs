def TJ(parts, word, l1, l2, tip='', head=None):
    """同訓異字：2つの文の下線部を漢字に直し、その二字を組み合わせて熟語を作る。parts は、(ひらがな, 漢字) の2つ。"""
    d = dict(kind='short', q=f'①　{l1}\n②　{l2}', ans=word, cells=2, meta=dict(t='TJ', parts=parts, word=word),
             ex=f'①「{parts[0][0]}」は「{parts[0][1]}」、②「{parts[1][0]}」は「{parts[1][1]}」。組み合わせて「{word}」。{tip}')
    return {**d, 'head': head} if head else d


def T(phrase, parts, word, tip='', head=None):
    """ひらがなの文を、二字の熟語に直す。parts は、文の中に出てくる順の (ひらがな, 漢字) の2つ。"""
    d = dict(kind='short', q=f'「{phrase}」', ans=word, cells=2, meta=dict(t='T', phrase=phrase, parts=parts, word=word),
             ex=f'「{parts[0][0]}」は「{parts[0][1]}」、「{parts[1][0]}」は「{parts[1][1]}」。熟語は「{word}」。{tip}')
    return {**d, 'head': head} if head else d


def Z(a, b, pairs, head=None):
    """A群の部首とB群の漢字を組み合わせてできる漢字を5つ。pairs は (部首名, 残りの部分, 漢字)。"""
    kanji = [k for _, _, k in pairs]
    d = dict(kind='grid', q='A群　' + '・'.join(a) + '\nB群　' + '・'.join(b), labels=['①', '②', '③', '④', '⑤'], per=5, ans=kanji,
             meta=dict(t='Z', a=a, b=b, pairs=pairs),
             ex='　'.join(f'{n}＋{r}＝{k}' for n, r, k in pairs) + '。（答えの順番は、ちがってもよい）')
    return {**d, 'head': head} if head else d


def _ul(word, ch):
    return word.replace(ch, '{' + ch + '}')


def D(target, kanji, opts, rds, ans, head=None):
    """同じ読み方の漢字：target の kanji と同じ読み方をする漢字をふくむ熟語を選ぶ。rds は、target と、各選択肢での、kanji の読み。"""
    row = '　'.join(f'{s} {_ul(o, kanji)}' for s, o in zip('アイウエ', opts))
    d = dict(kind='short', q=f'「{_ul(target, kanji)}」\n{row}', ans=ans, cells=1,
             meta=dict(t='D', target=target, kanji=kanji, opts=opts, rds=rds),
             ex=f'「{target}」の「{kanji}」は「{rds[0]}」。' + '　'.join(f'{s}「{o}」は「{r}」' for s, o, r in zip('アイウエ', opts, rds[1:])) + '。')
    return {**d, 'head': head} if head else d


