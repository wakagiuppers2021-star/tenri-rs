def _t(q):
    return re.search(r'\{(.+?)\}', q).group(1)


def W(q, ans, tip='', head=None):
    """書き取り：{カタカナ} を、漢字（と送りがな）に直す。"""
    d = dict(kind='short', q=q, ans=ans, cells=len(ans), ex=f'「{_t(q)}」は「{ans}」と書く。{tip or TIPS.get(ans, "")}')
    return {**d, 'head': head} if head else d


def R(q, ans, tip='', head=None):
    """読み：{漢字} の読みを、ひらがなで書く。"""
    d = dict(kind='short', q=q, ans=ans, cells=len(ans), ex=f'「{_t(q)}」は「{ans}」と読む。{tip or TIPS.get(ans, "")}')
    return {**d, 'head': head} if head else d


def O(q, ans, tip='', head=None):
    """送りがな：{ひらがな} を、漢字と送りがなで書く。"""
    d = dict(kind='short', q=q, ans=ans, cells=len(ans), ex=f'「{_t(q)}」は「{ans}」と書く。{tip or TIPS.get(ans, "")}')
    return {**d, 'head': head} if head else d


def P(q, word, opts, ans, tip='', head=None):
    """同じ漢字をふくむ熟語の選択。word は、カタカナを正しく書いたときの言葉。"""
    body = q + '\n' + '　'.join(f'{s} {o}' for s, o in zip('アイウエ', opts))
    d = dict(kind='short', q=body, ans=ans, cells=1, meta=dict(t='P', word=word, opts=opts),
             ex=f'カタカナは「{word}」と書く。同じ漢字をふくむのは「{opts["アイウエ".index(ans)]}」。{tip or TIPS.get(word, "")}')
    return {**d, 'head': head} if head else d


def B(kanji, name, example, others='', head=None):
    """部首：部首名と、同じ部首をもつ漢字。"""
    d = dict(kind='short', q=f'「{kanji}」', boxes=[('部首名', 92), ('同じ部首の漢字', 26)], ans=f'{name}　{example}',
             meta=dict(t='B', kanji=kanji, name=name, example=example, all=example + others.replace('・', '')),
             ex=f'「{kanji}」の部首は「{name}」。同じ部首の漢字には、{example}{others}などがある。（同じ部首なら、ほかの漢字でもよい）')
    return {**d, 'head': head} if head else d


def S(kanji, n, tip='', head=None):
    """画数：総画数。"""
    d = dict(kind='short', q=f'「{kanji}」', unit='画', ans=f'{n}画', meta=dict(t='S', kanji=kanji, n=n),
             ex=f'「{kanji}」の総画数は{n}画。{tip}')
    return {**d, 'head': head} if head else d


