def _t(q):
    return re.search(r'\{(.+?)\}', q).group(1)


def W(q, ans, tip='', head=None):
    """書き取り：{カタカナ} を、漢字（と送りがな）に直す。"""
    d = dict(kind='short', q=q, ans=ans, cells=len(ans), ex=f'「{_t(q)}」は「{ans}」と書く。{tip or TIPS.get(ans, "")}')
    return {**d, 'head': head} if head else d


